// Wrap runtime logic in an IIFE and use the shared `window.translations`
(function () {
  // Role: Current language state
  let currentLang = localStorage.getItem('lang') || 'en';

// Role: Switch language and update all elements with data-i18n attribute
function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);

  // Update language button icon/text
  const langBtn = document.getElementById('langToggle');
  if (langBtn) {
    langBtn.textContent = lang === 'en' ? '🇬🇧' : '🇪🇪';
  }

  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        element.placeholder = translations[lang][key];
      } else {
        element.textContent = translations[lang][key];
      }
    }
  });

  // Update HTML lang attribute
  document.documentElement.lang = lang;

  // Update page title based on page
  updatePageTitle(lang);

  // Dispatch event for other scripts
  window.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));
}

// Role: Update page title based on current page and language
function updatePageTitle(lang) {
  const path = window.location.pathname;
  let titleKey = '';

  if (path.includes('contact')) {
    titleKey = 'contact.title';
  } else if (path.includes('card-details')) {
    titleKey = 'Project Details - 3DXENON';
  } else if (path.includes('season')) {
    titleKey = 'Seasonal Video Viewer';
  } else if (path.includes('cash')) {
    titleKey = 'Spatial Media — Video Hero';
  } else {
    titleKey = '3DXENON— Video Feed';
  }

  if (lang === 'et') {
    if (path.includes('contact')) titleKey = 'Kontakt - 3DXENON';
    else if (path.includes('card-details')) titleKey = 'Projekti üksikasju - 3DXENON';
    else if (path.includes('season')) titleKey = 'Soojaga video vaataja';
    else if (path.includes('cash')) titleKey = 'Ruumiline meedia — Video kangelane';
    else titleKey = '3DXENON— Video voog';
  }

  document.title = titleKey;
}

// Role: Initialize language switcher on page load
function initLanguage() {
  // Create language toggle button if it doesn't exist
  if (!document.getElementById('langToggle')) {
    const nav = document.querySelector('nav') || document.querySelector('.contact-nav');
    if (nav) {
      const langBtn = document.createElement('button');
      langBtn.id = 'langToggle';
      langBtn.className = 'lang-toggle';
      langBtn.textContent = currentLang === 'en' ? '🇬🇧' : '🇪🇪';
      langBtn.setAttribute('aria-label', 'Switch language');
      nav.appendChild(langBtn);

      langBtn.addEventListener('click', () => {
        const newLang = currentLang === 'en' ? 'et' : 'en';
        setLanguage(newLang);
      });
    }
  }

  // Apply current language
  setLanguage(currentLang);
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLanguage);
} else {
  initLanguage();
}

})();
